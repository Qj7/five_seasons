export const formatPrice = (n: number) =>
  n.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ') + ' ₽'

export const splitPrice = (n: number) =>
  formatPrice(Math.round(n / 2)) + ' × 2 в сплит'

